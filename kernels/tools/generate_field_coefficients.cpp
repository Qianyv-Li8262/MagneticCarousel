#define REAL_LITERAL(value) value
#include "hysteresis_config.hpp"
#include "hysteresis_config_field.hpp"
#undef REAL_LITERAL

#include <cmath>
#include <iomanip>
#include <iostream>
#include <limits>
#include <string>

namespace
{
constexpr double two_pi = 6.283185307179586476925286766559;

struct coefficient
{
    double a;
    double c;
    double dz;
};

coefficient calculate(const int harmonic)
{
    const double n = static_cast<double>(harmonic);
    const double rho = two_pi * n * FIELD_Z0;
    const double k0 = std::cyl_bessel_k(0.0, rho);
    const double k1 = std::cyl_bessel_k(1.0, rho);
    const double a = n * n * k1;
    const double c = n * n * (k0 + k1 / rho);
    const double dz = -two_pi * n * (a + c / rho + a / (rho * rho));
    return {a, c, dz};
}

void write_preamble(const bool nvrtc)
{
    std::cout << "// Generated by generate_field_coefficients.cpp. DO NOT EDIT !!!\n"
                 "// Field Fourier expansion coefficients for field evaluating.\n"

                 "#pragma once\n\n"
                 "#include \"../headers/hysteresis_types.hpp\"\n\n"
                 "struct field_mode_coefficient {\n"
                 "    real_t a;\n"
                 "    real_t c;\n"
                 "    real_t dz;\n"
                 "};\n\n";

    if (nvrtc)
        std::cout << "static __device__ __constant__\n";
    else
        std::cout << "inline const\n";

    std::cout << "field_mode_coefficient FIELD_COEFFICIENTS["
              << FIELD_FOURIER_MODE_COUNT << "] = {\n";
}

void write_value(const double value, const bool)
{
    std::cout << "REAL_LITERAL(" << value << ')';
}
} // namespace

int main(int argc, char **argv)
{
    if (FIELD_Z0 <= 0.0 || FIELD_FOURIER_MODE_COUNT <= 0) {
        std::cerr << "FIELD_Z0 and FIELD_FOURIER_MODE_COUNT must be positive\n";
        return 1;
    }

    if (argc != 2 || (std::string(argv[1]) != "--cpu" && std::string(argv[1]) != "--nvrtc")) {
        std::cerr << "usage: generate_field_coefficients (--cpu | --nvrtc)\n";
        return 2;
    }

    const bool nvrtc = std::string(argv[1]) == "--nvrtc";
    std::cout << std::scientific
              << std::setprecision(std::numeric_limits<double>::max_digits10);
    write_preamble(nvrtc);

    for (int mode = 0; mode < FIELD_FOURIER_MODE_COUNT; ++mode) {
        const int harmonic = 2 * mode + 1;
        const coefficient value = calculate(harmonic);
        std::cout << "    {";
        write_value(value.a, nvrtc);
        std::cout << ", ";
        write_value(value.c, nvrtc);
        std::cout << ", ";
        write_value(value.dz, nvrtc);
        std::cout << "}, // n = " << harmonic << '\n';
    }

    std::cout << "};\n";
    return 0;
}
